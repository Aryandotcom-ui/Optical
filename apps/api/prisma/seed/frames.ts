/**
 * The launch frame range. Measurements are in millimetres, in the order
 * printed on a temple arm: lens width, bridge, temple length; then lens
 * height and total front width. Prices are whole rupees, tax-inclusive.
 */
export interface FrameModel {
  name: string;
  category: Exclude<CategorySlug, 'accessories'>;
  shape: FrameShape;
  material: FrameMaterial;
  rim: RimType;
  fit: FrameFit;
  /** [lens width, bridge, temple, lens height, total width] */
  mm: readonly [number, number, number, number, number];
  weightG: number;
  price: number;
  /** Eyeglass colourways, or [colourway, lens tint] pairs for sunglasses. */
  colours: readonly (ColourwayCode | readonly [ColourwayCode, SunTintCode])[];
  tags: readonly string[];
  /** One sentence that is only true of this frame. */
  line: string;
  springHinges?: boolean;
  /** Days since launch; under 45 shows as new. */
  launchedDaysAgo: number;
  popularity: number;
}

type Row = Omit<FrameModel, 'category'>;
