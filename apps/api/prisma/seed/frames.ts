  rows.map((row) => ({ ...row, category: 'eyeglasses' as const }));
const sunglasses = (rows: Row[]) =>
  rows.map((row) => ({ ...row, category: 'sunglasses' as const }));
const computer = (rows: Row[]) =>
  rows.map((row) => ({ ...row, category: 'computer-glasses' as const }));
const kids = (rows: Row[]) => rows.map((row) => ({ ...row, category: 'kids' as const }));

